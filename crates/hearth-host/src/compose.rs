//! docker compose projects: catalog apps plus hearth's own infrastructure
//! (gateway, cloudflared).
//!
//! App layout (`apps_dir/<id>/`):
//!
//! ```text
//! compose.yml         # verbatim from the manifest
//! hearth.override.yml # joins every service to the shared `hearth` network
//! data/               # ${APP_DATA}
//! .secret             # ${APP_SECRET}: random, generated once, stable across reinstalls
//! ```
//!
//! App data is never deleted by hearth; `remove` only stops and removes containers.

use std::path::{Path, PathBuf};

use hearth_core::AppManifest;
use serde::Serialize;

use crate::{CommandError, random_hex, run};

/// Docker network shared by the gateway and every app.
pub const NETWORK: &str = "hearth";

const OVERRIDE: &str = "# Generated by hearth. Puts all services on the shared gateway network.\n\
networks:\n  default:\n    name: hearth\n    external: true\n";

#[derive(Debug, thiserror::Error)]
pub enum ComposeError {
    #[error("cannot write {path}: {source}")]
    Io {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
    #[error(transparent)]
    Command(#[from] CommandError),
}

fn io(path: &Path) -> impl FnOnce(std::io::Error) -> ComposeError + '_ {
    move |source| ComposeError::Io {
        path: path.to_path_buf(),
        source,
    }
}

/// Override that pins services to exact image digests after a rollback.
pub const PIN_FILE: &str = "hearth.pin.yml";

/// Render the pin override: `service → image@sha256:…`.
#[must_use]
pub fn render_pins(pins: &[(String, String)]) -> String {
    let mut out = String::from(
        "# Generated by hearth after a failed update: keeps the last good images.\nservices:\n",
    );
    for (svc, image) in pins {
        use std::fmt::Write as _;
        let _ = write!(out, "  {svc}:\n    image: {image}\n");
    }
    out
}

/// Values substituted into compose files (`${NAME}`).
#[derive(Debug, Clone, Default, Serialize)]
pub struct ComposeEnv {
    pub vars: Vec<(String, String)>,
}

impl ComposeEnv {
    #[must_use]
    pub fn with(mut self, key: &str, value: impl Into<String>) -> Self {
        self.vars.push((key.to_owned(), value.into()));
        self
    }
}

/// A compose project on disk.
#[derive(Debug, Clone)]
pub struct Project {
    pub name: String,
    pub dir: PathBuf,
    pub files: Vec<PathBuf>,
}

impl Project {
    async fn compose(&self, env: &ComposeEnv, action: &[&str]) -> Result<String, ComposeError> {
        let files: Vec<String> = self.files.iter().map(|f| path_str(f)).collect();
        let mut args = vec!["compose", "-p", self.name.as_str()];
        for f in &files {
            args.extend(["-f", f.as_str()]);
        }
        args.extend_from_slice(action);
        let envs: Vec<(&str, &str)> = env
            .vars
            .iter()
            .map(|(k, v)| (k.as_str(), v.as_str()))
            .collect();
        Ok(run("docker", &args, &envs).await?)
    }

    pub async fn up(&self, env: &ComposeEnv) -> Result<(), ComposeError> {
        ensure_network().await?;
        self.compose(env, &["up", "-d", "--remove-orphans"]).await?;
        Ok(())
    }

    pub async fn pull(&self, env: &ComposeEnv) -> Result<(), ComposeError> {
        self.compose(env, &["pull", "-q"]).await?;
        Ok(())
    }

    pub async fn down(&self, env: &ComposeEnv) -> Result<(), ComposeError> {
        self.compose(env, &["down", "--remove-orphans"]).await?;
        Ok(())
    }

    pub async fn stop(&self, env: &ComposeEnv) -> Result<(), ComposeError> {
        self.compose(env, &["stop"]).await?;
        Ok(())
    }

    pub async fn restart(&self, env: &ComposeEnv) -> Result<(), ComposeError> {
        self.compose(env, &["restart"]).await?;
        Ok(())
    }

    /// `docker compose exec -T <service> <cmd...>`
    pub async fn exec(
        &self,
        env: &ComposeEnv,
        service: &str,
        cmd: &[&str],
    ) -> Result<String, ComposeError> {
        let mut action = vec!["exec", "-T", service];
        action.extend_from_slice(cmd);
        self.compose(env, &action).await
    }
}

/// Ensure the shared network exists (idempotent).
pub async fn ensure_network() -> Result<(), ComposeError> {
    if run("docker", &["network", "inspect", NETWORK], &[])
        .await
        .is_err()
    {
        run("docker", &["network", "create", NETWORK], &[]).await?;
    }
    Ok(())
}

/// What an install did or would do.
#[derive(Debug, Clone, Serialize)]
pub struct InstallPlan {
    pub project: String,
    pub dir: PathBuf,
    pub files: Vec<PathBuf>,
    pub command: String,
}

/// Manages catalog apps under `apps_dir`.
#[derive(Debug, Clone)]
pub struct ComposeRunner {
    apps_dir: PathBuf,
}

impl ComposeRunner {
    #[must_use]
    pub fn new(apps_dir: PathBuf) -> Self {
        Self { apps_dir }
    }

    #[must_use]
    pub fn app_dir(&self, id: &str) -> PathBuf {
        self.apps_dir.join(id)
    }

    /// The app's compose project. Includes `hearth.pin.yml` when an update was rolled
    /// back, so restarts keep running the known-good images.
    #[must_use]
    pub fn project(&self, app: &AppManifest) -> Project {
        let dir = self.app_dir(&app.id);
        let mut files = vec![dir.join("compose.yml"), dir.join("hearth.override.yml")];
        if dir.join(PIN_FILE).exists() {
            files.push(dir.join(PIN_FILE));
        }
        Project {
            name: app.project_name(),
            files,
            dir,
        }
    }

    /// Describe an install without touching anything.
    #[must_use]
    pub fn plan(&self, app: &AppManifest) -> InstallPlan {
        let p = self.project(app);
        InstallPlan {
            command: format!(
                "docker compose -p {} -f compose.yml -f hearth.override.yml up -d --remove-orphans",
                p.name
            ),
            project: p.name,
            dir: p.dir,
            files: p.files,
        }
    }

    /// Write files only (no Docker calls).
    pub async fn write_files(&self, app: &AppManifest) -> Result<InstallPlan, ComposeError> {
        let plan = self.plan(app);
        let data = plan.dir.join("data");
        tokio::fs::create_dir_all(&data).await.map_err(io(&data))?;
        ensure_secret(&plan.dir.join(".secret")).await?;
        for (path, body) in [
            (&plan.files[0], app.compose.as_str()),
            (&plan.files[1], OVERRIDE),
        ] {
            tokio::fs::write(path, body).await.map_err(io(path))?;
        }
        Ok(plan)
    }

    /// App-specific variables merged with the shared ones.
    pub async fn env_for(
        &self,
        app: &AppManifest,
        shared: &ComposeEnv,
    ) -> Result<ComposeEnv, ComposeError> {
        let dir = self.app_dir(&app.id);
        let secret = ensure_secret(&dir.join(".secret")).await?;
        Ok(shared
            .clone()
            .with("APP_DATA", path_str(&dir.join("data")))
            .with("APP_SECRET", secret))
    }

    pub async fn install(
        &self,
        app: &AppManifest,
        shared: &ComposeEnv,
    ) -> Result<InstallPlan, ComposeError> {
        let plan = self.write_files(app).await?;
        let env = self.env_for(app, shared).await?;
        let p = self.project(app);
        p.pull(&env).await?;
        p.up(&env).await?;
        Ok(plan)
    }

    pub async fn remove(&self, app: &AppManifest, shared: &ComposeEnv) -> Result<(), ComposeError> {
        let env = self.env_for(app, shared).await?;
        self.project(app).down(&env).await
    }

    pub async fn stop(&self, app: &AppManifest, shared: &ComposeEnv) -> Result<(), ComposeError> {
        let env = self.env_for(app, shared).await?;
        self.project(app).stop(&env).await
    }

    /// Start (or recreate after config changes).
    pub async fn start(&self, app: &AppManifest, shared: &ComposeEnv) -> Result<(), ComposeError> {
        let env = self.env_for(app, shared).await?;
        self.project(app).up(&env).await
    }

    pub async fn restart(
        &self,
        app: &AppManifest,
        shared: &ComposeEnv,
    ) -> Result<(), ComposeError> {
        let env = self.env_for(app, shared).await?;
        self.project(app).restart(&env).await
    }
}

/// Read a secret file, creating it (48 hex chars, mode 0600) if missing.
pub async fn ensure_secret(path: &Path) -> Result<String, ComposeError> {
    if let Ok(existing) = tokio::fs::read_to_string(path).await {
        return Ok(existing.trim().to_owned());
    }
    if let Some(parent) = path.parent() {
        tokio::fs::create_dir_all(parent)
            .await
            .map_err(io(parent))?;
    }
    let secret = random_hex(24).map_err(io(path))?;
    write_private(path, secret.as_bytes()).await?;
    Ok(secret)
}

/// Write a file readable only by the owner.
pub async fn write_private(path: &Path, body: &[u8]) -> Result<(), ComposeError> {
    use std::os::unix::fs::PermissionsExt as _;
    tokio::fs::write(path, body).await.map_err(io(path))?;
    tokio::fs::set_permissions(path, std::fs::Permissions::from_mode(0o600))
        .await
        .map_err(io(path))
}

#[must_use]
pub fn path_str(p: &Path) -> String {
    p.to_string_lossy().into_owned()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn app() -> AppManifest {
        AppManifest::from_yaml(
            "id: demo\nname: Demo\ndescription: d\ncategory: c\nport: 4000\n\
             upstream: { service: web, port: 80 }\ncompose: |\n  services:\n    web:\n      image: nginx\n",
        )
        .expect("valid")
    }

    #[test]
    fn pins_render_as_yaml() {
        let y = render_pins(&[("web".into(), "nginx@sha256:abc".into())]);
        assert!(y.contains("  web:\n    image: nginx@sha256:abc\n"));
    }

    #[tokio::test]
    async fn writes_compose_override_data_dir_and_stable_secret() {
        let tmp = tempfile::tempdir().expect("tempdir");
        let runner = ComposeRunner::new(tmp.path().to_path_buf());
        let plan = runner.write_files(&app()).await.expect("writes");
        assert_eq!(plan.project, "hearth-demo");
        assert!(
            std::fs::read_to_string(&plan.files[0])
                .expect("read")
                .contains("image: nginx")
        );
        assert!(
            std::fs::read_to_string(&plan.files[1])
                .expect("read")
                .contains("external: true")
        );
        assert!(plan.dir.join("data").is_dir());

        let env = runner
            .env_for(&app(), &ComposeEnv::default().with("TZ", "UTC"))
            .await
            .expect("env");
        let secret = env
            .vars
            .iter()
            .find(|(k, _)| k == "APP_SECRET")
            .map(|(_, v)| v.clone())
            .expect("secret");
        assert_eq!(secret.len(), 48);
        runner.write_files(&app()).await.expect("rewrites");
        let again = runner
            .env_for(&app(), &ComposeEnv::default())
            .await
            .expect("env");
        assert!(
            again
                .vars
                .iter()
                .any(|(k, v)| k == "APP_SECRET" && *v == secret),
            "secret is stable"
        );
        assert!(
            env.vars.iter().any(|(k, v)| k == "TZ" && v == "UTC"),
            "shared vars kept"
        );
    }
}
