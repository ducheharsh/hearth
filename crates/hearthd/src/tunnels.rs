//! Single-app public tunnels: Tailscale Funnel and ngrok.
//! (Cloudflare, with your own domain and the login in front, lives in `cloudflare.rs`.)

use anyhow::{Context as _, bail};
use hearth_gateway::NGROK_PORT;
use hearth_host::compose::{ComposeEnv, Project, write_private};
use serde::{Deserialize, Serialize};

use crate::events::Level;
use crate::state::{AppState, SharedState};
use crate::store;

#[derive(Debug, Default, Serialize, Deserialize)]
pub struct NgrokSecrets {
    pub authtoken: Option<String>,
}

fn ngrok_project(st: &AppState) -> Project {
    let dir = st.config.state_dir.join("ngrok");
    Project {
        name: "hearth-ngrok".into(),
        files: vec![dir.join("compose.yml")],
        dir,
    }
}

fn ngrok_compose(domain: &str) -> String {
    format!(
        "# Generated by hearth.\nservices:\n  ngrok:\n    image: ngrok/ngrok:latest\n    restart: unless-stopped\n    \
         command: [\"http\", \"--url={domain}\", \"caddy:{NGROK_PORT}\"]\n    env_file: [.env]\n\
         networks:\n  default:\n    name: hearth\n    external: true\n"
    )
}

async fn save_tunnels(
    st: &SharedState,
    f: impl FnOnce(&mut crate::settings::Tunnels),
) -> anyhow::Result<()> {
    let mut s = st.settings.write().await;
    f(&mut s.tunnels);
    store::save(&st.config.state_dir.join("settings.json"), &*s)?;
    Ok(())
}

async fn require_gateway(st: &SharedState, app: &str) -> anyhow::Result<()> {
    if !st.settings.read().await.gateway_enabled {
        bail!("Turn the gateway on first; tunnels go through it.");
    }
    if !st.installed().await.0.contains(app)
        && !st.persisted.read().await.routes.iter().any(|r| r.id == app)
    {
        bail!("Install the app first.");
    }
    Ok(())
}

/// Publish `app` to the internet at `https://<node>.ts.net` with Tailscale Funnel.
pub async fn set_funnel(st: &SharedState, app: Option<String>) -> anyhow::Result<()> {
    if let Some(a) = &app {
        require_gateway(st, a).await?;
    }
    save_tunnels(st, |t| t.funnel_app.clone_from(&app)).await?;
    crate::gateway::apply(st).await?;
    st.event(
        Level::Warning,
        "tunnels",
        if app.is_some() {
            "Funnel on"
        } else {
            "Funnel off"
        },
        app.map_or_else(
            || "Nothing is public via Funnel.".into(),
            |a| format!("{a} is public on the internet. It relies on its own login."),
        ),
    )
    .await;
    Ok(())
}

/// Publish `app` with ngrok on your static domain.
pub async fn set_ngrok(
    st: &SharedState,
    app: Option<String>,
    domain: Option<String>,
    authtoken: Option<String>,
) -> anyhow::Result<()> {
    let proj = ngrok_project(st);
    let Some(app) = app else {
        if proj.dir.join("compose.yml").exists() {
            proj.down(&ComposeEnv::default()).await?;
        }
        save_tunnels(st, |t| t.ngrok_app = None).await?;
        crate::gateway::reapply_quietly(st).await;
        st.event(
            Level::Info,
            "tunnels",
            "ngrok off",
            "The ngrok tunnel is stopped.",
        )
        .await;
        return Ok(());
    };
    require_gateway(st, &app).await?;
    let domain = domain
        .map(|d| d.trim().to_ascii_lowercase())
        .filter(|d| crate::settings::valid_domain(d))
        .context("Enter your ngrok static domain (e.g. name.ngrok-free.app).")?;
    let secrets_path = st.config.secrets_dir().join("ngrok.json");
    let mut secrets: NgrokSecrets = store::load(&secrets_path)?;
    if let Some(t) = authtoken.filter(|t| !t.trim().is_empty()) {
        secrets.authtoken = Some(t.trim().to_owned());
        store::save(&secrets_path, &secrets)?;
    }
    let token = secrets
        .authtoken
        .context("Paste your ngrok authtoken (dashboard.ngrok.com → Your Authtoken).")?;

    save_tunnels(st, |t| {
        t.ngrok_app = Some(app.clone());
        t.ngrok_domain = Some(domain.clone());
    })
    .await?;
    crate::gateway::apply(st).await?;
    tokio::fs::create_dir_all(&proj.dir).await?;
    tokio::fs::write(proj.dir.join("compose.yml"), ngrok_compose(&domain)).await?;
    write_private(
        &proj.dir.join(".env"),
        format!("NGROK_AUTHTOKEN={token}\n").as_bytes(),
    )
    .await?;
    proj.up(&ComposeEnv::default())
        .await
        .context("starting ngrok")?;
    st.event(
        Level::Warning,
        "tunnels",
        "ngrok on",
        format!("{app} is public at https://{domain}. It relies on its own login."),
    )
    .await;
    Ok(())
}

#[cfg(test)]
mod tests {
    #[test]
    fn ngrok_compose_targets_caddy() {
        let y = super::ngrok_compose("x.ngrok-free.app");
        assert!(y.contains("--url=x.ngrok-free.app"));
        assert!(y.contains("caddy:18080"));
        assert!(y.contains("external: true"));
    }
}
