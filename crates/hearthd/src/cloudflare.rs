//! Custom domain via Cloudflare Tunnel, fully automated with an API token:
//! find the zone → create/reuse a tunnel → route `*.domain` to Caddy → wildcard DNS →
//! run the `cloudflared` connector on the `hearth` network.
//!
//! Required token permissions: Account › Cloudflare Tunnel › Edit, Zone › DNS › Edit,
//! Zone › Zone › Read.

use std::path::PathBuf;

use anyhow::{Context as _, anyhow, bail};
use hearth_host::compose::{ComposeEnv, Project, write_private};
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};

use crate::events::Level;
use crate::settings::valid_domain;
use crate::state::{AppState, SharedState};
use crate::store;

const API: &str = "https://api.cloudflare.com/client/v4";

#[derive(Debug, Default, Serialize, Deserialize)]
pub struct Secrets {
    pub api_token: Option<String>,
    pub tunnel_token: Option<String>,
}

fn secrets_path(st: &AppState) -> PathBuf {
    st.config.secrets_dir().join("cloudflare.json")
}

pub fn load_secrets(st: &AppState) -> anyhow::Result<Secrets> {
    store::load(&secrets_path(st))
}

struct Api {
    http: reqwest::Client,
    token: String,
}

impl Api {
    async fn call(
        &self,
        method: reqwest::Method,
        path: &str,
        body: Option<Value>,
    ) -> anyhow::Result<Value> {
        let mut req = self
            .http
            .request(method, format!("{API}{path}"))
            .bearer_auth(&self.token);
        if let Some(b) = body {
            req = req.json(&b);
        }
        let v: Value = req.send().await?.json().await?;
        if v["success"].as_bool() != Some(true) {
            let msg = v["errors"]
                .as_array()
                .and_then(|e| e.first())
                .and_then(|e| e["message"].as_str())
                .unwrap_or("request failed");
            bail!("Cloudflare: {msg}");
        }
        Ok(v["result"].clone())
    }
}

fn connector(st: &AppState) -> Project {
    let dir = st.config.state_dir.join("cloudflared");
    Project {
        name: "hearth-cloudflared".into(),
        files: vec![dir.join("compose.yml")],
        dir,
    }
}

const CONNECTOR_COMPOSE: &str = "# Generated by hearth.\nservices:\n  cloudflared:\n    image: cloudflare/cloudflared:latest\n    restart: unless-stopped\n    command: [\"tunnel\", \"--no-autoupdate\", \"run\"]\n    env_file: [.env]\nnetworks:\n  default:\n    name: hearth\n    external: true\n";

async fn start_connector(st: &AppState, tunnel_token: &str) -> anyhow::Result<()> {
    let p = connector(st);
    tokio::fs::create_dir_all(&p.dir).await?;
    tokio::fs::write(p.dir.join("compose.yml"), CONNECTOR_COMPOSE).await?;
    write_private(
        &p.dir.join(".env"),
        format!("TUNNEL_TOKEN={tunnel_token}\n").as_bytes(),
    )
    .await?;
    p.up(&ComposeEnv::default()).await?;
    Ok(())
}

#[derive(Debug, Serialize)]
pub struct Connected {
    pub domain: String,
    pub tunnel_id: String,
}

/// Set everything up for `domain` using `api_token`.
#[allow(clippy::too_many_lines)] // one linear provisioning script
pub async fn connect(st: &SharedState, api_token: &str, domain: &str) -> anyhow::Result<Connected> {
    let domain = domain.trim().trim_end_matches('.').to_ascii_lowercase();
    if !valid_domain(&domain) {
        bail!("`{domain}` isn't a valid domain.");
    }
    let api = Api {
        http: reqwest::Client::builder().user_agent("hearth").build()?,
        token: api_token.trim().to_owned(),
    };
    api.call(reqwest::Method::GET, "/user/tokens/verify", None)
        .await
        .context("verifying API token")?;

    // The zone may be the domain itself or a parent (home.example.com → example.com).
    let labels: Vec<&str> = domain.split('.').collect();
    let mut zone = None;
    for i in 0..labels.len().saturating_sub(1) {
        let candidate = labels[i..].join(".");
        let r = api
            .call(
                reqwest::Method::GET,
                &format!("/zones?name={candidate}"),
                None,
            )
            .await?;
        if let Some(z) = r.as_array().and_then(|a| a.first()) {
            zone = Some(z.clone());
            break;
        }
    }
    let zone = zone.ok_or_else(|| {
        anyhow!("No Cloudflare zone found for {domain}. Add the domain to Cloudflare first.")
    })?;
    let zone_id = zone["id"].as_str().context("zone id")?.to_owned();
    let account_id = zone["account"]["id"]
        .as_str()
        .context("account id")?
        .to_owned();

    let name = format!(
        "hearth-{}",
        sysinfo::System::host_name()
            .unwrap_or_else(|_| "server".into())
            .replace('.', "-")
    );
    let existing = api
        .call(
            reqwest::Method::GET,
            &format!("/accounts/{account_id}/cfd_tunnel?name={name}&is_deleted=false"),
            None,
        )
        .await?;
    let tunnel_id = match existing.as_array().and_then(|a| a.first()) {
        Some(t) => t["id"].as_str().context("tunnel id")?.to_owned(),
        None => api
            .call(
                reqwest::Method::POST,
                &format!("/accounts/{account_id}/cfd_tunnel"),
                Some(json!({ "name": name, "config_src": "cloudflare" })),
            )
            .await?["id"]
            .as_str()
            .context("tunnel id")?
            .to_owned(),
    };
    let tunnel_token = api
        .call(
            reqwest::Method::GET,
            &format!("/accounts/{account_id}/cfd_tunnel/{tunnel_id}/token"),
            None,
        )
        .await?
        .as_str()
        .context("tunnel token")?
        .to_owned();

    api.call(
        reqwest::Method::PUT,
        &format!("/accounts/{account_id}/cfd_tunnel/{tunnel_id}/configurations"),
        Some(json!({ "config": { "ingress": [
            { "hostname": format!("*.{domain}"), "service": "http://caddy:80" },
            { "service": "http_status:404" }
        ]}})),
    )
    .await
    .context("configuring tunnel routes")?;

    let record = json!({
        "type": "CNAME", "name": format!("*.{domain}"),
        "content": format!("{tunnel_id}.cfargotunnel.com"), "proxied": true,
        "comment": "Managed by hearth"
    });
    let found = api
        .call(
            reqwest::Method::GET,
            &format!("/zones/{zone_id}/dns_records?type=CNAME&name=*.{domain}"),
            None,
        )
        .await?;
    let record_id = match found.as_array().and_then(|a| a.first()) {
        Some(r) => {
            let id = r["id"].as_str().context("record id")?.to_owned();
            api.call(
                reqwest::Method::PUT,
                &format!("/zones/{zone_id}/dns_records/{id}"),
                Some(record),
            )
            .await?;
            id
        }
        None => api
            .call(
                reqwest::Method::POST,
                &format!("/zones/{zone_id}/dns_records"),
                Some(record),
            )
            .await?["id"]
            .as_str()
            .context("record id")?
            .to_owned(),
    };

    store::save(
        &secrets_path(st),
        &Secrets {
            api_token: Some(api.token.clone()),
            tunnel_token: Some(tunnel_token.clone()),
        },
    )?;
    {
        let mut s = st.settings.write().await;
        s.domain = Some(domain.clone());
        s.cloudflare.account_id = Some(account_id);
        s.cloudflare.zone_id = Some(zone_id);
        s.cloudflare.tunnel_id = Some(tunnel_id.clone());
        s.cloudflare.dns_record_id = Some(record_id);
        s.cloudflare.enabled = true;
        store::save(&st.config.state_dir.join("settings.json"), &*s)?;
    }
    start_connector(st, &tunnel_token)
        .await
        .context("starting cloudflared")?;
    crate::gateway::reapply_quietly(st).await;
    st.event(
        Level::Success,
        "cloudflare",
        "Domain connected",
        format!("Apps you mark public are reachable at <app>.{domain}, behind your login."),
    )
    .await;
    Ok(Connected { domain, tunnel_id })
}

/// Stop the connector; with `delete`, also remove the DNS record and the tunnel.
pub async fn disconnect(st: &SharedState, delete: bool) -> anyhow::Result<()> {
    let p = connector(st);
    if p.dir.join("compose.yml").exists() {
        p.down(&ComposeEnv::default()).await?;
    }
    let cf = st.settings.read().await.cloudflare.clone();
    if delete && let Some(token) = load_secrets(st)?.api_token {
        let api = Api {
            http: reqwest::Client::builder().user_agent("hearth").build()?,
            token,
        };
        if let (Some(zone), Some(rec)) = (&cf.zone_id, &cf.dns_record_id) {
            let _ = api
                .call(
                    reqwest::Method::DELETE,
                    &format!("/zones/{zone}/dns_records/{rec}"),
                    None,
                )
                .await;
        }
        if let (Some(acc), Some(t)) = (&cf.account_id, &cf.tunnel_id) {
            let _ = api
                .call(
                    reqwest::Method::DELETE,
                    &format!("/accounts/{acc}/cfd_tunnel/{t}/connections"),
                    None,
                )
                .await;
            let _ = api
                .call(
                    reqwest::Method::DELETE,
                    &format!("/accounts/{acc}/cfd_tunnel/{t}"),
                    None,
                )
                .await;
        }
        store::save(&secrets_path(st), &Secrets::default())?;
    }
    {
        let mut s = st.settings.write().await;
        s.cloudflare.enabled = false;
        s.domain = None;
        if delete {
            s.cloudflare = crate::settings::CloudflareSettings::default();
        }
        store::save(&st.config.state_dir.join("settings.json"), &*s)?;
    }
    crate::gateway::reapply_quietly(st).await;
    st.event(
        Level::Info,
        "cloudflare",
        "Domain disconnected",
        if delete {
            "Tunnel and DNS record removed."
        } else {
            "Connector stopped; tunnel kept."
        },
    )
    .await;
    Ok(())
}
