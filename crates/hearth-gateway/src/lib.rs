//! The gateway: one Caddy in front of everything, every route checked by Authelia.
//!
//! ```text
//! Tailnet:  https://<TS_HOST>:<port> --tailscale serve--> 127.0.0.1:<port> (Caddy)
//! Domain:   https://<sub>.<domain> --Cloudflare Tunnel--> caddy:80 (host routing)
//!           ...both --forward_auth--> authelia:9091 --ok--> <upstream> on network `hearth`
//! ```
//!
//! Pure rendering (Caddyfile, compose, Authelia config/users) so output is deterministic
//! and testable. Applying it is the daemon's job.

use std::fmt::Write as _;

use argon2::password_hash::PasswordHasher;
use argon2::{Algorithm, Argon2, Params, Version};
use hearth_core::AppManifest;
use serde::{Deserialize, Serialize};

/// Public port of the Authelia login portal on the tailnet.
pub const AUTH_PORT: u16 = 9091;
/// Public port of the hearth dashboard on the tailnet.
pub const HEARTH_PORT: u16 = 9443;
/// Where the native hearth daemon listens, as seen from containers.
pub const HEARTH_UPSTREAM: &str = "host.docker.internal:9000";
/// Subdomain for the login portal and the dashboard on a custom domain.
pub const AUTH_SUBDOMAIN: &str = "auth";
pub const HEARTH_SUBDOMAIN: &str = "hearth";

/// One published site.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Route {
    pub id: String,
    pub name: String,
    /// Public tailnet port (== Caddy listen port).
    pub port: u16,
    /// `host:port` reachable from the Caddy container.
    pub upstream: String,
    /// Require an Authelia session.
    pub protect: bool,
    /// Paths that bypass Authelia (Caddy path matcher syntax).
    pub exempt_paths: Vec<String>,
    /// Subdomain label used when a custom domain is configured.
    pub subdomain: String,
    /// Reachable from the internet via the custom domain (still behind Authelia).
    pub public: bool,
    /// Override the Host header sent upstream (e.g. Syncthing wants `localhost`).
    #[serde(default)]
    pub host_header: Option<String>,
    /// Who may open it after signing in: `None` = every login; `Some(list)` = only these
    /// usernames. Admins always may. See [`apply_access`].
    #[serde(default)]
    pub allow: Option<Vec<String>>,
}

impl Route {
    #[must_use]
    pub fn for_app(app: &AppManifest) -> Self {
        Self {
            id: app.id.clone(),
            name: app.name.clone(),
            port: app.port,
            upstream: format!("{}:{}", app.upstream.service, app.upstream.port),
            protect: app.auth.protect,
            exempt_paths: app.auth.exempt_paths.clone(),
            subdomain: app.id.clone(),
            public: false,
            host_header: None,
            allow: None,
        }
    }
}

/// The two built-in routes (login portal, dashboard).
#[must_use]
pub fn builtin_routes() -> Vec<Route> {
    vec![
        Route {
            id: "authelia".into(),
            name: "Login (Authelia)".into(),
            port: AUTH_PORT,
            upstream: "authelia:9091".into(),
            protect: false,
            exempt_paths: vec![],
            subdomain: AUTH_SUBDOMAIN.into(),
            public: true,
            host_header: None,
            allow: None,
        },
        Route {
            id: "hearth".into(),
            name: "hearth".into(),
            port: HEARTH_PORT,
            upstream: HEARTH_UPSTREAM.into(),
            protect: true,
            exempt_paths: vec![],
            subdomain: HEARTH_SUBDOMAIN.into(),
            public: false,
            host_header: None,
            allow: None,
        },
    ]
}

/// Built-ins plus the given app routes, sorted by port.
#[must_use]
pub fn routes(apps: impl IntoIterator<Item = Route>) -> Vec<Route> {
    let mut all = builtin_routes();
    all.extend(apps);
    all.sort_by_key(|r| r.port);
    all
}

const PRELUDE: &str = "\
# Generated by hearth. Do not edit; changes are overwritten.
{
\tauto_https off
\tadmin localhost:2019
}

# Tailnet sites: original URL is https://$TS_HOST:<port>
(login) {
\tforward_auth authelia:9091 {
\t\turi /api/authz/forward-auth
\t\tcopy_headers Remote-User Remote-Groups Remote-Email Remote-Name
\t\theader_up X-Forwarded-Proto https
\t\theader_up X-Forwarded-Host {$TS_HOST}:{args[0]}
\t}
}

(app) {
\treverse_proxy {args[0]} {
\t\theader_up Host {args[2]}
\t\theader_up X-Forwarded-Proto https
\t\theader_up X-Forwarded-Host {$TS_HOST}:{args[1]}
\t}
}

# Domain sites (via Cloudflare Tunnel): original URL is https://{host}
(login_host) {
\tforward_auth authelia:9091 {
\t\turi /api/authz/forward-auth
\t\tcopy_headers Remote-User Remote-Groups Remote-Email Remote-Name
\t\theader_up X-Forwarded-Proto https
\t\theader_up X-Forwarded-Host {host}
\t}
}

(app_host) {
\treverse_proxy {args[0]} {
\t\theader_up Host {args[1]}
\t\theader_up X-Forwarded-Proto https
\t\theader_up X-Forwarded-Host {host}
\t}
}
";

fn site_body(out: &mut String, r: &Route, login: &str, app: &str) {
    if !r.protect {
        let _ = writeln!(out, "\timport {app}");
    } else if r.exempt_paths.is_empty() {
        let _ = writeln!(out, "\timport {login}{}\n\timport {app}", guard(r, "\t"));
    } else {
        let _ = writeln!(
            out,
            "\t@public path {paths}\n\thandle @public {{\n\t\timport {app}\n\t}}\n\
             \thandle {{\n\t\timport {login}{guard}\n\t\timport {app}\n\t}}",
            paths = r.exempt_paths.join(" "),
            guard = guard(r, "\t\t")
        );
    }
}

/// Per-app access, after sign-in: Authelia sets `Remote-User` / `Remote-Groups` (overwriting
/// anything the client sent), and Caddy refuses anyone who isn't listed or an admin.
fn guard(r: &Route, indent: &str) -> String {
    let Some(allow) = &r.allow else {
        return String::new();
    };
    let users = if allow.is_empty() {
        String::new()
    } else {
        format!(
            "\n{indent}\tnot header_regexp Remote-User ^({})$",
            allow.join("|")
        )
    };
    format!(
        "\n{indent}@denied {{{users}\n{indent}\tnot header_regexp Remote-Groups (^|,)\\s*admins\\s*(,|$)\n{indent}}}\n\
         {indent}respond @denied \"You don't have access to {name}. Ask an admin of this hearth.\" 403",
        name = r.name.replace('"', "")
    )
}

/// Render the full Caddyfile. `domain` adds host-routed sites for public routes.
///
/// ```
/// let r = hearth_gateway::routes([]);
/// let caddy = hearth_gateway::render_caddyfile(&r, None);
/// assert!(caddy.contains("http://:9091"));
/// assert!(caddy.contains("import login 9443"));
/// ```
#[must_use]
pub fn render_caddyfile(routes: &[Route], domain: Option<&str>) -> String {
    let mut out = String::from(PRELUDE);
    for r in routes {
        let (port, up) = (r.port, &r.upstream);
        let host = r
            .host_header
            .clone()
            .unwrap_or_else(|| format!("{{$TS_HOST}}:{port}"));
        let _ = writeln!(out, "\n# {} (tailnet)\nhttp://:{port} {{", r.name);
        site_body(
            &mut out,
            r,
            &format!("login {port}"),
            &format!("app {up} {port} {host}"),
        );
        out.push_str("}\n");
    }
    if let Some(domain) = domain {
        for r in routes.iter().filter(|r| r.public || r.id == "hearth") {
            let fqdn = format!("{}.{domain}", r.subdomain);
            let host = r.host_header.clone().unwrap_or_else(|| "{host}".into());
            let _ = writeln!(out, "\n# {} (domain)\nhttp://{fqdn} {{", r.name);
            site_body(
                &mut out,
                r,
                "login_host",
                &format!("app_host {} {host}", r.upstream),
            );
            out.push_str("}\n");
        }
        let _ = writeln!(
            out,
            "\n# Anything else on the domain\nhttp:// {{\n\trespond \"Not found\" 404\n}}"
        );
    }
    out
}

/// A login-less site for single-app public tunnels (Tailscale Funnel, ngrok).
/// These rely on the app's own authentication.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct OpenSite {
    pub name: String,
    /// Caddy listen port.
    pub listen: u16,
    pub upstream: String,
    /// Publish on 127.0.0.1 (Funnel needs it); ngrok reaches Caddy over the network.
    pub publish: bool,
}

/// Exposing the gateway on a `NetBird` peer IP. `NetBird` has no cert service, so Caddy
/// serves HTTPS from its internal CA (users trust it once per device).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct NetbirdTarget {
    pub ip: String,
    pub fqdn: String,
}

/// Caddy's internal listen port for a route's `NetBird` site (host side keeps the public port).
#[must_use]
pub const fn netbird_port(port: u16) -> u16 {
    port.wrapping_add(40_000)
}

/// One way to reach the hearth dashboard.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct AccessLink {
    /// `tailscale` | `domain` | `netbird` | `local`
    pub kind: &'static str,
    pub url: String,
    /// Who can use it, in plain words.
    pub reach: &'static str,
}

/// What can reach the dashboard right now, best first.
///
/// `ts_host` / `netbird_fqdn` are only passed when that network is connected; nothing but the
/// local address works until the gateway is on.
#[must_use]
pub fn access_links(
    gateway_enabled: bool,
    ts_host: Option<&str>,
    domain: Option<&str>,
    netbird_fqdn: Option<&str>,
    local: &str,
) -> Vec<AccessLink> {
    let mut out = Vec::new();
    if gateway_enabled {
        if let Some(h) = ts_host {
            out.push(AccessLink {
                kind: "tailscale",
                url: format!("https://{h}:{HEARTH_PORT}"),
                reach: "Works on any device signed in to your Tailscale",
            });
        }
        if let Some(d) = domain {
            out.push(AccessLink {
                kind: "domain",
                url: format!("https://{HEARTH_SUBDOMAIN}.{d}"),
                reach: "Works anywhere, after you sign in",
            });
        }
        if let Some(f) = netbird_fqdn {
            out.push(AccessLink {
                kind: "netbird",
                url: format!("https://{f}:{}", netbird_port(HEARTH_PORT)),
                reach: "Works on devices in your NetBird network",
            });
        }
    }
    out.push(AccessLink {
        kind: "local",
        url: local.to_owned(),
        reach: "Only on this Mac",
    });
    out
}

/// Extra Caddyfile blocks for `NetBird` access (internal-CA HTTPS on `<fqdn>:<port>`).
#[must_use]
pub fn render_netbird_sites(routes: &[Route], nb: &NetbirdTarget) -> String {
    let fqdn = &nb.fqdn;
    let mut out = format!(
        "\n# NetBird access: https://{fqdn}:<port> (Caddy internal CA)\n\
(login_nb) {{\n\tforward_auth authelia:9091 {{\n\t\turi /api/authz/forward-auth\n\t\t\
copy_headers Remote-User Remote-Groups Remote-Email Remote-Name\n\t\theader_up X-Forwarded-Proto https\n\t\t\
header_up X-Forwarded-Host {fqdn}:{{args[0]}}\n\t}}\n}}\n\
(app_nb) {{\n\treverse_proxy {{args[0]}} {{\n\t\theader_up Host {{args[2]}}\n\t\theader_up X-Forwarded-Proto https\n\t\t\
header_up X-Forwarded-Host {fqdn}:{{args[1]}}\n\t}}\n}}\n"
    );
    for r in routes.iter().filter(|r| r.port <= 25_535) {
        let (port, up) = (r.port, &r.upstream);
        let host = r
            .host_header
            .clone()
            .unwrap_or_else(|| format!("{fqdn}:{port}"));
        let _ = writeln!(
            out,
            "\n# {} (NetBird)\nhttps://{fqdn}:{} {{\n\ttls internal",
            r.name,
            netbird_port(port)
        );
        site_body(
            &mut out,
            r,
            &format!("login_nb {port}"),
            &format!("app_nb {up} {port} {host}"),
        );
        out.push_str("}\n");
    }
    out
}

