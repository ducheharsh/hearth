/// Extra Caddyfile blocks for open sites.
#[must_use]
pub fn render_open_sites(sites: &[OpenSite]) -> String {
    sites.iter().fold(String::new(), |mut out, s| {
        let _ = writeln!(
            out,
            "\n# {} (public tunnel, app's own login)\nhttp://:{} {{\n\treverse_proxy {} {{\n\t\theader_up X-Forwarded-Proto https\n\t}}\n}}",
            s.name, s.listen, s.upstream
        );
        out
    })
}

/// Render the gateway compose project (Caddy + Authelia).
#[must_use]
pub fn render_compose(
    routes: &[Route],
    open: &[OpenSite],
    netbird: Option<&NetbirdTarget>,
) -> String {
    let mut ports: String = routes.iter().fold(String::new(), |mut s, r| {
        let _ = writeln!(
            s,
            "      - \"127.0.0.1:{p}:{p}\"   # {}",
            r.name,
            p = r.port
        );
        s
    });
    if let Some(nb) = netbird {
        for r in routes.iter().filter(|r| r.port <= 25_535) {
            let _ = writeln!(
                ports,
                "      - \"{}:{}:{}\"   # {} (NetBird)",
                nb.ip,
                r.port,
                netbird_port(r.port),
                r.name
            );
        }
    }
    for o in open.iter().filter(|o| o.publish) {
        let _ = writeln!(
            ports,
            "      - \"127.0.0.1:{p}:{p}\"   # {} (tunnel)",
            o.name,
            p = o.listen
        );
    }
    // A raw string keeps the YAML indentation exactly as written (a `\` line
    // continuation would strip it).
    format!(
        r"# Generated by hearth. Do not edit; changes are overwritten.
name: hearth-gateway
services:
  caddy:
    image: caddy:2
    restart: unless-stopped
    depends_on: [authelia]
    environment:
      TS_HOST: ${{TS_HOST}}
    ports:
{ports}    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - ./caddy-data:/data
  authelia:
    image: authelia/authelia:4.39
    restart: unless-stopped
    env_file: [authelia.env]
    volumes:
      - ./authelia:/config
networks:
  default:
    name: hearth
    external: true
"
    )
}

/// Authelia `configuration.yml`. Secrets come from `authelia.env`.
