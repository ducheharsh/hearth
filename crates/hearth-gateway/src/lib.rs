//! The gateway: one Caddy in front of everything, every route checked by Authelia.
//!
//! ```text
//! Tailnet:  https://<TS_HOST>:<port> --tailscale serve--> 127.0.0.1:<port> (Caddy)
//! Domain:   https://<sub>.<domain> --Cloudflare Tunnel--> caddy:80 (host routing)
//!           ...both --forward_auth--> authelia:9091 --ok--> <upstream> on network `hearth`
//! ```
//!
//! Pure rendering (Caddyfile, compose, Authelia config/users) so output is deterministic
//! and testable. Applying it is the daemon's job.

use std::fmt::Write as _;

use argon2::password_hash::PasswordHasher;
use argon2::{Algorithm, Argon2, Params, Version};
use hearth_core::AppManifest;
use serde::{Deserialize, Serialize};

/// Public port of the Authelia login portal on the tailnet.
pub const AUTH_PORT: u16 = 9091;
/// Public port of the hearth dashboard on the tailnet.
pub const HEARTH_PORT: u16 = 9443;
/// Where the native hearth daemon listens, as seen from containers.
pub const HEARTH_UPSTREAM: &str = "host.docker.internal:9000";
/// Subdomain for the login portal and the dashboard on a custom domain.
pub const AUTH_SUBDOMAIN: &str = "auth";
pub const HEARTH_SUBDOMAIN: &str = "hearth";

/// One published site.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Route {
    pub id: String,
    pub name: String,
    /// Public tailnet port (== Caddy listen port).
    pub port: u16,
    /// `host:port` reachable from the Caddy container.
    pub upstream: String,
    /// Require an Authelia session.
    pub protect: bool,
    /// Paths that bypass Authelia (Caddy path matcher syntax).
    pub exempt_paths: Vec<String>,
    /// Subdomain label used when a custom domain is configured.
    pub subdomain: String,
    /// Reachable from the internet via the custom domain (still behind Authelia).
    pub public: bool,
    /// Override the Host header sent upstream (e.g. Syncthing wants `localhost`).
    #[serde(default)]
    pub host_header: Option<String>,
}

impl Route {
    #[must_use]
    pub fn for_app(app: &AppManifest) -> Self {
        Self {
            id: app.id.clone(),
            name: app.name.clone(),
            port: app.port,
            upstream: format!("{}:{}", app.upstream.service, app.upstream.port),
            protect: app.auth.protect,
            exempt_paths: app.auth.exempt_paths.clone(),
            subdomain: app.id.clone(),
            public: false,
            host_header: None,
        }
    }
}

/// The two built-in routes (login portal, dashboard).
#[must_use]
pub fn builtin_routes() -> Vec<Route> {
    vec![
        Route {
            id: "authelia".into(),
            name: "Login (Authelia)".into(),
            port: AUTH_PORT,
            upstream: "authelia:9091".into(),
            protect: false,
            exempt_paths: vec![],
            subdomain: AUTH_SUBDOMAIN.into(),
            public: true,
            host_header: None,
        },
        Route {
            id: "hearth".into(),
            name: "hearth".into(),
            port: HEARTH_PORT,
            upstream: HEARTH_UPSTREAM.into(),
            protect: true,
            exempt_paths: vec![],
            subdomain: HEARTH_SUBDOMAIN.into(),
            public: false,
            host_header: None,
        },
    ]
}

/// Built-ins plus the given app routes, sorted by port.
#[must_use]
pub fn routes(apps: impl IntoIterator<Item = Route>) -> Vec<Route> {
    let mut all = builtin_routes();
    all.extend(apps);
    all.sort_by_key(|r| r.port);
    all
}

const PRELUDE: &str = "\
# Generated by hearth. Do not edit; changes are overwritten.
{
\tauto_https off
\tadmin localhost:2019
}

# Tailnet sites: original URL is https://$TS_HOST:<port>
(login) {
\tforward_auth authelia:9091 {
\t\turi /api/authz/forward-auth
\t\tcopy_headers Remote-User Remote-Groups Remote-Email Remote-Name
\t\theader_up X-Forwarded-Proto https
\t\theader_up X-Forwarded-Host {$TS_HOST}:{args[0]}
\t}
}

(app) {
\treverse_proxy {args[0]} {
\t\theader_up Host {args[2]}
\t\theader_up X-Forwarded-Proto https
\t\theader_up X-Forwarded-Host {$TS_HOST}:{args[1]}
\t}
}

# Domain sites (via Cloudflare Tunnel): original URL is https://{host}
(login_host) {
\tforward_auth authelia:9091 {
\t\turi /api/authz/forward-auth
\t\tcopy_headers Remote-User Remote-Groups Remote-Email Remote-Name
\t\theader_up X-Forwarded-Proto https
\t\theader_up X-Forwarded-Host {host}
\t}
}

(app_host) {
\treverse_proxy {args[0]} {
\t\theader_up Host {args[1]}
\t\theader_up X-Forwarded-Proto https
\t\theader_up X-Forwarded-Host {host}
\t}
}
";

fn site_body(out: &mut String, r: &Route, login: &str, app: &str) {
    if !r.protect {
        let _ = writeln!(out, "\timport {app}");
    } else if r.exempt_paths.is_empty() {
        let _ = writeln!(out, "\timport {login}\n\timport {app}");
    } else {
        let _ = writeln!(
            out,
            "\t@public path {paths}\n\thandle @public {{\n\t\timport {app}\n\t}}\n\
             \thandle {{\n\t\timport {login}\n\t\timport {app}\n\t}}",
            paths = r.exempt_paths.join(" ")
        );
    }
}

/// Render the full Caddyfile. `domain` adds host-routed sites for public routes.
///
/// ```
/// let r = hearth_gateway::routes([]);
/// let caddy = hearth_gateway::render_caddyfile(&r, None);
/// assert!(caddy.contains("http://:9091"));
/// assert!(caddy.contains("import login 9443"));
/// ```
#[must_use]
pub fn render_caddyfile(routes: &[Route], domain: Option<&str>) -> String {
    let mut out = String::from(PRELUDE);
    for r in routes {
        let (port, up) = (r.port, &r.upstream);
        let host = r
            .host_header
            .clone()
            .unwrap_or_else(|| format!("{{$TS_HOST}}:{port}"));
        let _ = writeln!(out, "\n# {} (tailnet)\nhttp://:{port} {{", r.name);
        site_body(
            &mut out,
            r,
            &format!("login {port}"),
            &format!("app {up} {port} {host}"),
        );
        out.push_str("}\n");
    }
    if let Some(domain) = domain {
        for r in routes.iter().filter(|r| r.public || r.id == "hearth") {
            let fqdn = format!("{}.{domain}", r.subdomain);
            let host = r.host_header.clone().unwrap_or_else(|| "{host}".into());
            let _ = writeln!(out, "\n# {} (domain)\nhttp://{fqdn} {{", r.name);
            site_body(
                &mut out,
                r,
                "login_host",
                &format!("app_host {} {host}", r.upstream),
            );
            out.push_str("}\n");
        }
        let _ = writeln!(
            out,
            "\n# Anything else on the domain\nhttp:// {{\n\trespond \"Not found\" 404\n}}"
        );
    }
    out
}

/// A login-less site for single-app public tunnels (Tailscale Funnel, ngrok).
/// These rely on the app's own authentication.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct OpenSite {
    pub name: String,
    /// Caddy listen port.
    pub listen: u16,
    pub upstream: String,
    /// Publish on 127.0.0.1 (Funnel needs it); ngrok reaches Caddy over the network.
    pub publish: bool,
}

/// Exposing the gateway on a `NetBird` peer IP. `NetBird` has no cert service, so Caddy
/// serves HTTPS from its internal CA (users trust it once per device).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct NetbirdTarget {
    pub ip: String,
    pub fqdn: String,
}

/// Caddy's internal listen port for a route's `NetBird` site (host side keeps the public port).
#[must_use]
pub const fn netbird_port(port: u16) -> u16 {
    port.wrapping_add(40_000)
}

/// Extra Caddyfile blocks for `NetBird` access (internal-CA HTTPS on `<fqdn>:<port>`).
#[must_use]
pub fn render_netbird_sites(routes: &[Route], nb: &NetbirdTarget) -> String {
    let fqdn = &nb.fqdn;
    let mut out = format!(
        "\n# NetBird access: https://{fqdn}:<port> (Caddy internal CA)\n\
(login_nb) {{\n\tforward_auth authelia:9091 {{\n\t\turi /api/authz/forward-auth\n\t\t\
copy_headers Remote-User Remote-Groups Remote-Email Remote-Name\n\t\theader_up X-Forwarded-Proto https\n\t\t\
header_up X-Forwarded-Host {fqdn}:{{args[0]}}\n\t}}\n}}\n\
(app_nb) {{\n\treverse_proxy {{args[0]}} {{\n\t\theader_up Host {{args[2]}}\n\t\theader_up X-Forwarded-Proto https\n\t\t\
header_up X-Forwarded-Host {fqdn}:{{args[1]}}\n\t}}\n}}\n"
    );
    for r in routes.iter().filter(|r| r.port <= 25_535) {
        let (port, up) = (r.port, &r.upstream);
        let host = r
            .host_header
            .clone()
            .unwrap_or_else(|| format!("{fqdn}:{port}"));
        let _ = writeln!(
            out,
            "\n# {} (NetBird)\nhttps://{fqdn}:{} {{\n\ttls internal",
            r.name,
            netbird_port(port)
        );
        site_body(
            &mut out,
            r,
            &format!("login_nb {port}"),
            &format!("app_nb {up} {port} {host}"),
        );
        out.push_str("}\n");
    }
    out
}

/// Port Caddy listens on for the Tailscale Funnel site.
pub const FUNNEL_PORT: u16 = 18443;
/// Port Caddy listens on for the ngrok site (container network only).
pub const NGROK_PORT: u16 = 18080;

/// Extra Caddyfile blocks for open sites.
#[must_use]
pub fn render_open_sites(sites: &[OpenSite]) -> String {
    sites.iter().fold(String::new(), |mut out, s| {
        let _ = writeln!(
            out,
            "\n# {} (public tunnel, app's own login)\nhttp://:{} {{\n\treverse_proxy {} {{\n\t\theader_up X-Forwarded-Proto https\n\t}}\n}}",
            s.name, s.listen, s.upstream
        );
        out
    })
}

/// Render the gateway compose project (Caddy + Authelia).
#[must_use]
pub fn render_compose(
    routes: &[Route],
    open: &[OpenSite],
    netbird: Option<&NetbirdTarget>,
) -> String {
    let mut ports: String = routes.iter().fold(String::new(), |mut s, r| {
        let _ = writeln!(
            s,
            "      - \"127.0.0.1:{p}:{p}\"   # {}",
            r.name,
            p = r.port
        );
        s
    });
    if let Some(nb) = netbird {
        for r in routes.iter().filter(|r| r.port <= 25_535) {
            let _ = writeln!(
                ports,
                "      - \"{}:{}:{}\"   # {} (NetBird)",
                nb.ip,
                r.port,
                netbird_port(r.port),
                r.name
            );
        }
    }
    for o in open.iter().filter(|o| o.publish) {
        let _ = writeln!(
            ports,
            "      - \"127.0.0.1:{p}:{p}\"   # {} (tunnel)",
            o.name,
            p = o.listen
        );
    }
    format!(
        "# Generated by hearth. Do not edit; changes are overwritten.\n\
name: hearth-gateway\n\
services:\n\
  caddy:\n\
    image: caddy:2\n\
    restart: unless-stopped\n\
    depends_on: [authelia]\n\
    environment:\n\
      TS_HOST: ${{TS_HOST}}\n\
    ports:\n{ports}\
    volumes:\n\
      - ./Caddyfile:/etc/caddy/Caddyfile:ro\n\
      - ./caddy-data:/data\n\
  authelia:\n\
    image: authelia/authelia:4.39\n\
    restart: unless-stopped\n\
    env_file: [authelia.env]\n\
    volumes:\n\
      - ./authelia:/config\n\
networks:\n\
  default:\n\
    name: hearth\n\
    external: true\n"
    )
}

/// Authelia `configuration.yml`. Secrets come from `authelia.env`.
#[must_use]
pub fn render_authelia_config(
    ts_host: &str,
    domain: Option<&str>,
    netbird_fqdn: Option<&str>,
) -> String {
    let mut rules = format!("    - domain: '{ts_host}'\n      policy: two_factor\n");
    let mut cookies = format!(
        "    - domain: '{ts_host}'\n      authelia_url: 'https://{ts_host}:{AUTH_PORT}'\n      \
         default_redirection_url: 'https://{ts_host}:{HEARTH_PORT}'\n"
    );
    if let Some(nb) = netbird_fqdn {
        let _ = write!(rules, "    - domain: '{nb}'\n      policy: two_factor\n");
        let _ = write!(
            cookies,
            "    - domain: '{nb}'\n      authelia_url: 'https://{nb}:{AUTH_PORT}'\n      \
             default_redirection_url: 'https://{nb}:{HEARTH_PORT}'\n"
        );
    }
    if let Some(d) = domain {
        let _ = write!(
            rules,
            "    - domain: ['{d}', '*.{d}']\n      policy: two_factor\n"
        );
        let _ = write!(
            cookies,
            "    - domain: '{d}'\n      authelia_url: 'https://{AUTH_SUBDOMAIN}.{d}'\n      \
             default_redirection_url: 'https://{HEARTH_SUBDOMAIN}.{d}'\n"
        );
    }
    format!(
        "# Generated by hearth. Do not edit; changes are overwritten.\n\
theme: auto\n\
server:\n  address: 'tcp://0.0.0.0:9091'\n\
log:\n  level: info\n\
ntp:\n  disable_failure: true\n\
totp:\n  issuer: hearth\n\
webauthn:\n  display_name: hearth\n\
authentication_backend:\n  file:\n    path: /config/users.yml\n    watch: true\n    password:\n      algorithm: argon2\n\
access_control:\n  default_policy: deny\n  rules:\n{rules}\
session:\n  expiration: 30d\n  inactivity: 7d\n  remember_me: 30d\n  cookies:\n{cookies}\
regulation:\n  max_retries: 5\n  find_time: 10m\n  ban_time: 30m\n\
storage:\n  local:\n    path: /config/db.sqlite3\n\
notifier:\n  filesystem:\n    filename: /config/notification.txt\n"
    )
}

/// A login for the gateway.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct User {
    pub username: String,
    pub display_name: String,
    pub email: String,
    /// PHC-format argon2id hash.
    pub password_hash: String,
    /// An authenticator app has been enrolled and verified.
    #[serde(default)]
    pub totp: bool,
}

#[derive(Debug, thiserror::Error)]
pub enum UserError {
    #[error("username must be 2-32 chars of [a-z0-9._-]")]
    BadUsername,
    #[error("password must be at least 12 characters")]
    WeakPassword,
    #[error("email looks invalid")]
    BadEmail,
    #[error("hashing failed: {0}")]
    Hash(String),
}

/// Validate and hash a new user's credentials. `salt` must be 16 random bytes.
pub fn new_user(
    username: &str,
    display_name: &str,
    email: &str,
    password: &str,
    salt: &[u8; 16],
) -> Result<User, UserError> {
    let ok_name = (2..=32).contains(&username.len())
        && username.bytes().all(|b| {
            b.is_ascii_lowercase() || b.is_ascii_digit() || matches!(b, b'.' | b'_' | b'-')
        });
    if !ok_name {
        return Err(UserError::BadUsername);
    }
    if password.chars().count() < 12 {
        return Err(UserError::WeakPassword);
    }
    if !email.contains('@') || email.contains(char::is_whitespace) {
        return Err(UserError::BadEmail);
    }
    Ok(User {
        username: username.to_owned(),
        display_name: if display_name.trim().is_empty() {
            username.to_owned()
        } else {
            display_name.trim().to_owned()
        },
        email: email.to_owned(),
        password_hash: hash_password(password, salt)?,
        totp: false,
    })
}

/// argon2id with Authelia's default parameters (m=64 MiB, t=3, p=4).
pub fn hash_password(password: &str, salt: &[u8; 16]) -> Result<String, UserError> {
    let params = Params::new(65_536, 3, 4, Some(32)).map_err(|e| UserError::Hash(e.to_string()))?;
    Argon2::new(Algorithm::Argon2id, Version::V0x13, params)
        .hash_password_with_salt(password.as_bytes(), salt)
        .map(|h| h.to_string())
        .map_err(|e| UserError::Hash(e.to_string()))
}

fn yaml_str(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

/// Authelia `users.yml`.
#[must_use]
pub fn render_users(users: &[User]) -> String {
    let mut out = String::from("# Generated by hearth. Manage users in hearth Settings.\nusers:\n");
    if users.is_empty() {
        out.truncate(out.len() - 1);
        out.push_str(" {}\n");
    }
    for u in users {
        let _ = write!(
            out,
            "  {}:\n    displayname: {}\n    email: {}\n    password: {}\n    groups: [admins]\n",
            u.username,
            yaml_str(&u.display_name),
            yaml_str(&u.email),
            yaml_str(&u.password_hash)
        );
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn app(yaml_extra: &str) -> AppManifest {
        AppManifest::from_yaml(&format!(
            "id: vaultwarden\nname: Vaultwarden\ndescription: d\ncategory: security\nport: 8081\n\
             upstream: {{ service: vaultwarden, port: 80 }}\n{yaml_extra}\
             compose: |\n  services:\n    vaultwarden:\n      image: vaultwarden/server\n"
        ))
        .expect("valid")
    }

    #[test]
    fn builtins_always_present_and_sorted() {
        let r = routes([Route::for_app(&app(""))]);
        let ports: Vec<u16> = r.iter().map(|r| r.port).collect();
        assert_eq!(ports, [8081, AUTH_PORT, HEARTH_PORT]);
        assert!(!r[1].protect, "login portal itself must be public");
    }

    #[test]
    fn protected_app_without_exemptions() {
        let c = render_caddyfile(&routes([Route::for_app(&app(""))]), None);
        assert!(c.contains(
            "http://:8081 {\n\timport login 8081\n\timport app vaultwarden:80 8081 {$TS_HOST}:8081\n}"
        ), "{c}");
    }

    #[test]
    fn exempt_paths_bypass_login_only_for_matches() {
        let a = app("auth: { exempt_paths: [\"/api/*\", \"/identity/*\"] }\n");
        let c = render_caddyfile(&routes([Route::for_app(&a)]), None);
        assert!(c.contains("@public path /api/* /identity/*"));
        let site = c.split("http://:8081").nth(1).expect("site block");
        assert!(
            site.find("handle @public").expect("public")
                < site.find("import login 8081").expect("login")
        );
    }

    #[test]
    fn domain_sites_only_for_public_routes_and_dashboard() {
        let mut private = Route::for_app(&app(""));
        private.subdomain = "vault".into();
        let mut public = private.clone();
        public.id = "kuma".into();
        public.subdomain = "status".into();
        public.port = 3002;
        public.public = true;
        let c = render_caddyfile(&routes([private, public]), Some("example.com"));
        assert!(c.contains("http://status.example.com {\n\timport login_host"));
        assert!(
            c.contains("http://hearth.example.com {"),
            "dashboard reachable on the domain"
        );
        assert!(
            c.contains("http://auth.example.com {"),
            "login portal on the domain"
        );
        assert!(
            !c.contains("vault.example.com"),
            "private apps stay tailnet-only"
        );
        assert!(c.contains("respond \"Not found\" 404"));
    }

    #[test]
    fn host_header_override() {
        let mut r = Route::for_app(&app(""));
        r.host_header = Some("localhost:8384".into());
        let c = render_caddyfile(&[r], None);
        assert!(c.contains("import app vaultwarden:80 8081 localhost:8384"));
    }

    #[test]
    fn compose_publishes_every_route_on_loopback_only() {
        let y = render_compose(&routes([Route::for_app(&app(""))]), &[], None);
        for p in [8081, AUTH_PORT, HEARTH_PORT] {
            assert!(y.contains(&format!("\"127.0.0.1:{p}:{p}\"")), "port {p}");
        }
        assert!(!y.contains("\"0.0.0.0"));
    }

    #[test]
    fn authelia_config_covers_tailnet_and_domain() {
        let c = render_authelia_config("m1.tail.ts.net", Some("example.com"), None);
        assert!(c.contains("authelia_url: 'https://m1.tail.ts.net:9091'"));
        assert!(c.contains("authelia_url: 'https://auth.example.com'"));
        assert!(c.contains("domain: ['example.com', '*.example.com']"));
        assert!(c.contains("default_policy: deny"));
        let c = render_authelia_config("m1.tail.ts.net", None, None);
        assert!(!c.contains("example.com"));
    }

    #[test]
    fn netbird_sites_use_internal_tls_and_bind_peer_ip() {
        let nb = NetbirdTarget {
            ip: "100.92.0.5".into(),
            fqdn: "m1.netbird.cloud".into(),
        };
        let r = routes([Route::for_app(&app(""))]);
        let c = render_netbird_sites(&r, &nb);
        assert!(
            c.contains("https://m1.netbird.cloud:48081 {\n\ttls internal\n\timport login_nb 8081")
        );
        assert!(c.contains("header_up X-Forwarded-Host m1.netbird.cloud:{args[0]}"));
        let y = render_compose(&r, &[], Some(&nb));
        assert!(y.contains("\"100.92.0.5:8081:48081\""));
        let a = render_authelia_config("m1.ts.net", None, Some("m1.netbird.cloud"));
        assert!(a.contains("authelia_url: 'https://m1.netbird.cloud:9091'"));
    }

    #[test]
    fn users_hash_and_render() {
        let u = new_user(
            "harsh",
            "Harsh",
            "h@example.com",
            "correct horse battery",
            &[7; 16],
        )
        .expect("valid");
        assert!(
            u.password_hash
                .starts_with("$argon2id$v=19$m=65536,t=3,p=4$"),
            "{}",
            u.password_hash
        );
        let y = render_users(&[u]);
        assert!(y.contains("  harsh:\n    displayname: 'Harsh'"));
        assert!(new_user("Bad Name", "", "a@b", "correct horse battery", &[0; 16]).is_err());
        assert!(matches!(
            new_user("ok", "", "a@b", "short", &[0; 16]),
            Err(UserError::WeakPassword)
        ));
        assert_eq!(
            render_users(&[]),
            "# Generated by hearth. Manage users in hearth Settings.\nusers: {}\n"
        );
    }
}
