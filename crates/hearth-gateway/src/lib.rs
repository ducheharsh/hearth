//! The gateway: one Caddy in front of everything, every route checked by Authelia.
//!
//! ```text
//! Tailnet:  https://<TS_HOST>:<port> --tailscale serve--> 127.0.0.1:<port> (Caddy)
//! Domain:   https://<sub>.<domain> --Cloudflare Tunnel--> caddy:80 (host routing)
//!           ...both --forward_auth--> authelia:9091 --ok--> <upstream> on network `hearth`
//! ```
//!
//! Pure rendering (Caddyfile, compose, Authelia config/users) so output is deterministic
//! and testable. Applying it is the daemon's job.

use std::fmt::Write as _;

use argon2::password_hash::PasswordHasher;
use argon2::{Algorithm, Argon2, Params, Version};
use hearth_core::AppManifest;
use serde::{Deserialize, Serialize};

/// Public port of the Authelia login portal on the tailnet.
pub const AUTH_PORT: u16 = 9091;
/// Public port of the hearth dashboard on the tailnet.
pub const HEARTH_PORT: u16 = 9443;
/// Where the native hearth daemon listens, as seen from containers.
pub const HEARTH_UPSTREAM: &str = "host.docker.internal:9000";
/// Subdomain for the login portal and the dashboard on a custom domain.
pub const AUTH_SUBDOMAIN: &str = "auth";
pub const HEARTH_SUBDOMAIN: &str = "hearth";

/// One published site.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Route {
    pub id: String,
    pub name: String,
    /// Public tailnet port (== Caddy listen port).
    pub port: u16,
    /// `host:port` reachable from the Caddy container.
    pub upstream: String,
    /// Require an Authelia session.
    pub protect: bool,
    /// Paths that bypass Authelia (Caddy path matcher syntax).
    pub exempt_paths: Vec<String>,
    /// Subdomain label used when a custom domain is configured.
    pub subdomain: String,
    /// Reachable from the internet via the custom domain (still behind Authelia).
    pub public: bool,
    /// Override the Host header sent upstream (e.g. Syncthing wants `localhost`).
    #[serde(default)]
    pub host_header: Option<String>,
    /// Who may open it after signing in: `None` = every login; `Some(list)` = only these
    /// usernames. Admins always may. See [`apply_access`].
    #[serde(default)]
    pub allow: Option<Vec<String>>,
}

impl Route {
    #[must_use]
    pub fn for_app(app: &AppManifest) -> Self {
        Self {
            id: app.id.clone(),
            name: app.name.clone(),
            port: app.port,
            upstream: format!("{}:{}", app.upstream.service, app.upstream.port),
            protect: app.auth.protect,
            exempt_paths: app.auth.exempt_paths.clone(),
            subdomain: app.id.clone(),
            public: false,
            host_header: None,
            allow: None,
        }
    }
}

/// The two built-in routes (login portal, dashboard).
#[must_use]
pub fn builtin_routes() -> Vec<Route> {
    vec![
        Route {
            id: "authelia".into(),
            name: "Login (Authelia)".into(),
            port: AUTH_PORT,
            upstream: "authelia:9091".into(),
            protect: false,
            exempt_paths: vec![],
            subdomain: AUTH_SUBDOMAIN.into(),
            public: true,
            host_header: None,
            allow: None,
        },
        Route {
            id: "hearth".into(),
            name: "hearth".into(),
            port: HEARTH_PORT,
            upstream: HEARTH_UPSTREAM.into(),
            protect: true,
            exempt_paths: vec![],
            subdomain: HEARTH_SUBDOMAIN.into(),
            public: false,
            host_header: None,
            allow: None,
        },
    ]
}

/// Built-ins plus the given app routes, sorted by port.
#[must_use]
pub fn routes(apps: impl IntoIterator<Item = Route>) -> Vec<Route> {
    let mut all = builtin_routes();
    all.extend(apps);
    all.sort_by_key(|r| r.port);
    all
}

/// Global options. Access logs (user, session cookie, browser) stream to hearthd on
/// `log_port` for the signed-in devices list; without it they're discarded.
fn prelude(log_port: Option<u16>) -> String {
    let access = log_port.map_or_else(
        || "\t\toutput discard\n".to_owned(),
        |p| {
            format!(
                "\t\toutput net tcp/host.docker.internal:{p} {{\n\t\t\tsoft_start\n\t\t}}\n\t\tformat json\n"
            )
        },
    );
    format!(
        "# Generated by hearth. Do not edit; changes are overwritten.\n{{\n\
\t# Certificates only where a site asks for them (tls internal); the rest is plain HTTP\n\
\t# behind tailscale serve or a tunnel. No redirects, no host trust store.\n\
\tauto_https disable_redirects\n\tskip_install_trust\n\tadmin localhost:2019\n\
\tlog default {{\n\t\texclude http.log.access\n\t}}\n\
\tlog access {{\n{access}\t\tinclude http.log.access\n\t}}\n}}\n\n{SNIPPETS}"
    )
}

/// Identity headers only Authelia may set: removed from every incoming request first, so a
/// client can't claim to be someone on unprotected routes or exempt paths.
const STRIP: &str = "request_header -Remote-User\n\trequest_header -Remote-Groups\n\t\
request_header -Remote-Email\n\trequest_header -Remote-Name";

/// Per-site access log fields read by hearthd (`sessions.rs`). `gate` marks requests that
/// went through the login and `authed` the ones Authelia let in. Caddy redacts the Cookie
/// header itself; the session cookie goes only to hearthd, which keeps a hash.
const LOG: &str = "\tlog\n\tlog_append user {http.request.header.Remote-User}\n\t\
log_append sid {http.request.cookie.authelia_session}\n\tlog_append gate {http.vars.gate}\n\t\
log_append authed {http.vars.authed}\n";

const SNIPPETS: &str = "\
# Tailnet sites: original URL is https://$TS_HOST:<port>
(login) {
\troute {
\t\tvars gate 1
\t\trequest_header -Remote-User
\t\trequest_header -Remote-Groups
\t\trequest_header -Remote-Email
\t\trequest_header -Remote-Name
\t\tforward_auth authelia:9091 {
\t\t\turi /api/authz/forward-auth
\t\t\tcopy_headers Remote-User Remote-Groups Remote-Email Remote-Name
\t\t\theader_up X-Forwarded-Proto https
\t\t\theader_up X-Forwarded-Host {$TS_HOST}:{args[0]}
\t\t}
\t\tvars authed 1
\t}
}

(app) {
\treverse_proxy {args[0]} {
\t\theader_up Host {args[2]}
\t\theader_up X-Forwarded-Proto https
\t\theader_up X-Forwarded-Host {$TS_HOST}:{args[1]}
\t}
}

# Domain sites (via Cloudflare Tunnel): original URL is https://{host}
(login_host) {
\troute {
\t\tvars gate 1
\t\trequest_header -Remote-User
\t\trequest_header -Remote-Groups
\t\trequest_header -Remote-Email
\t\trequest_header -Remote-Name
\t\tforward_auth authelia:9091 {
\t\t\turi /api/authz/forward-auth
\t\t\tcopy_headers Remote-User Remote-Groups Remote-Email Remote-Name
\t\t\theader_up X-Forwarded-Proto https
\t\t\theader_up X-Forwarded-Host {host}
\t\t}
\t\tvars authed 1
\t}
}

(app_host) {
\treverse_proxy {args[0]} {
\t\theader_up Host {args[1]}
\t\theader_up X-Forwarded-Proto https
\t\theader_up X-Forwarded-Host {host}
\t}
}
";

fn site_body(out: &mut String, r: &Route, login: &str, app: &str) {
    out.push_str(LOG);
    if !r.protect {
        let _ = writeln!(out, "\t{STRIP}\n\timport {app}");
    } else if r.exempt_paths.is_empty() {
        let _ = writeln!(out, "\timport {login}{}\n\timport {app}", guard(r, "\t"));
    } else {
        let _ = writeln!(
            out,
            "\t@public path {paths}\n\thandle @public {{\n\t\t{strip}\n\t\timport {app}\n\t}}\n\
             \thandle {{\n\t\timport {login}{guard}\n\t\timport {app}\n\t}}",
            paths = r.exempt_paths.join(" "),
            strip = STRIP.replace("\n\t", "\n\t\t"),
            guard = guard(r, "\t\t")
        );
    }
}

/// Per-app access, after sign-in: Authelia sets `Remote-User` / `Remote-Groups` (overwriting
/// anything the client sent), and Caddy refuses anyone who isn't listed or an admin.
fn guard(r: &Route, indent: &str) -> String {
    let Some(allow) = &r.allow else {
        return String::new();
    };
    let users = if allow.is_empty() {
        String::new()
    } else {
        format!(
            "\n{indent}\tnot header_regexp Remote-User ^({})$",
            allow.join("|")
        )
    };
    format!(
        "\n{indent}@denied {{{users}\n{indent}\tnot header_regexp Remote-Groups (^|,)\\s*admins\\s*(,|$)\n{indent}}}\n\
         {indent}respond @denied \"You don't have access to {name}. Ask an admin of this hearth.\" 403",
        name = r.name.replace('"', "")
    )
}

/// Render the full Caddyfile. `domain` adds host-routed sites for public routes.
///
/// ```
/// let r = hearth_gateway::routes([]);
/// let caddy = hearth_gateway::render_caddyfile(&r, None, Some(9001));
/// assert!(caddy.contains("http://:9091"));
/// assert!(caddy.contains("import login 9443"));
/// ```
#[must_use]
pub fn render_caddyfile(routes: &[Route], domain: Option<&str>, log_port: Option<u16>) -> String {
    let mut out = prelude(log_port);
    for r in routes {
        let (port, up) = (r.port, &r.upstream);
        let host = r
            .host_header
            .clone()
            .unwrap_or_else(|| format!("{{$TS_HOST}}:{port}"));
        let _ = writeln!(out, "\n# {} (tailnet)\nhttp://:{port} {{", r.name);
        site_body(
            &mut out,
            r,
            &format!("login {port}"),
            &format!("app {up} {port} {host}"),
        );
        out.push_str("}\n");
    }
    if let Some(domain) = domain {
        for r in routes.iter().filter(|r| r.public || r.id == "hearth") {
            let fqdn = format!("{}.{domain}", r.subdomain);
            let host = r.host_header.clone().unwrap_or_else(|| "{host}".into());
            let _ = writeln!(out, "\n# {} (domain)\nhttp://{fqdn} {{", r.name);
            site_body(
                &mut out,
                r,
                "login_host",
                &format!("app_host {} {host}", r.upstream),
            );
            out.push_str("}\n");
        }
        let _ = writeln!(
            out,
            "\n# Anything else on the domain\nhttp:// {{\n\trespond \"Not found\" 404\n}}"
        );
    }
    out
}

/// A login-less site for single-app public tunnels (Tailscale Funnel, ngrok).
/// These rely on the app's own authentication.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct OpenSite {
    pub name: String,
    /// Caddy listen port.
    pub listen: u16,
    pub upstream: String,
    /// Publish on 127.0.0.1 (Funnel needs it); ngrok reaches Caddy over the network.
    pub publish: bool,
}

/// Serving the gateway straight on a private-network address with HTTPS from hearth's own
/// certificate authority (Caddy's internal CA), for networks without a certificate service:
/// `NetBird`, or a tailnet where HTTPS certificates can't be turned on. Users trust the CA
/// once per device (downloadable at `http://<ip>:CERT_PORT`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CaTarget {
    /// Address the published ports bind to (never `0.0.0.0`).
    pub ip: String,
    /// Name the certificate is issued for.
    pub fqdn: String,
}

/// Where devices download hearth's CA certificate (plain HTTP, private network only).
pub const CERT_PORT: u16 = 9444;

/// Caddy's internal listen port for a route's CA site (host side keeps the public port).
/// Ports above 25535 have no CA site.
#[must_use]
pub const fn ca_port(port: u16) -> u16 {
    port.wrapping_add(40_000)
}

/// Routes that get a CA site.
fn ca_routes(routes: &[Route]) -> impl Iterator<Item = &Route> {
    routes.iter().filter(|r| r.port <= 25_535)
}

/// One way to reach the hearth dashboard.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct AccessLink {
    /// `tailscale` | `domain` | `netbird` | `local`
    pub kind: &'static str,
    pub url: String,
    /// Who can use it, in plain words.
    pub reach: &'static str,
    /// Set when the link uses hearth's own certificate: where each device downloads it.
    pub trust_url: Option<String>,
}

/// The networks that are connected right now (see [`access_links`]).
#[derive(Debug, Clone, Copy, Default)]
pub struct Reach<'a> {
    pub gateway_enabled: bool,
    pub ts_host: Option<&'a str>,
    /// Tailscale IP when the tailnet uses hearth's certificate instead of its own.
    pub ts_ca_ip: Option<&'a str>,
    pub domain: Option<&'a str>,
    pub netbird: Option<&'a CaTarget>,
    pub local: &'a str,
}

/// What can reach the dashboard right now, best first. Nothing but the local address works
/// until the gateway is on.
#[must_use]
pub fn access_links(r: &Reach<'_>) -> Vec<AccessLink> {
    let trust = |ip: &str| Some(format!("http://{ip}:{CERT_PORT}"));
    let mut out = Vec::new();
    if r.gateway_enabled {
        if let Some(h) = r.ts_host {
            out.push(AccessLink {
                kind: "tailscale",
                url: format!("https://{h}:{HEARTH_PORT}"),
                reach: "Works on any device signed in to your Tailscale",
                trust_url: r.ts_ca_ip.and_then(trust),
            });
        }
        if let Some(d) = r.domain {
            out.push(AccessLink {
                kind: "domain",
                url: format!("https://{HEARTH_SUBDOMAIN}.{d}"),
                reach: "Works anywhere, after you sign in",
                trust_url: None,
            });
        }
        if let Some(nb) = r.netbird {
            out.push(AccessLink {
                kind: "netbird",
                url: format!("https://{}:{HEARTH_PORT}", nb.fqdn),
                reach: "Works on devices in your NetBird network",
                trust_url: trust(&nb.ip),
            });
        }
    }
    out.push(AccessLink {
        kind: "local",
        url: r.local.to_owned(),
        reach: "Only on this Mac",
        trust_url: None,
    });
    out
}

/// Extra Caddyfile blocks for CA access: `https://<fqdn>:<port>` with `tls internal` for
/// every target, plus the certificate download site. Empty without targets.
#[must_use]
pub fn render_ca_sites(routes: &[Route], targets: &[CaTarget]) -> String {
    if targets.is_empty() {
        return String::new();
    }
    let mut out = String::from(
        "\n# hearth's own certificate: https://<name>:<port> (Caddy internal CA)\n\
(login_ca) {\n\troute {\n\t\tvars gate 1\n\t\trequest_header -Remote-User\n\t\trequest_header -Remote-Groups\n\t\t\
request_header -Remote-Email\n\t\trequest_header -Remote-Name\n\t\tforward_auth authelia:9091 {\n\t\t\t\
uri /api/authz/forward-auth\n\t\t\tcopy_headers Remote-User Remote-Groups Remote-Email Remote-Name\n\t\t\t\
header_up X-Forwarded-Proto https\n\t\t\theader_up X-Forwarded-Host {host}:{args[0]}\n\t\t}\n\t\tvars authed 1\n\t}\n}\n\
(app_ca) {\n\treverse_proxy {args[0]} {\n\t\theader_up Host {args[2]}\n\t\theader_up X-Forwarded-Proto https\n\t\t\
header_up X-Forwarded-Host {host}:{args[1]}\n\t}\n}\n",
    );
    for r in ca_routes(routes) {
        let (port, up) = (r.port, &r.upstream);
        let host = r
            .host_header
            .clone()
            .unwrap_or_else(|| format!("{{host}}:{port}"));
        let addrs: Vec<String> = targets
            .iter()
            .map(|t| format!("https://{}:{}", t.fqdn, ca_port(port)))
            .collect();
        let _ = writeln!(
            out,
            "\n# {} (hearth certificate)\n{} {{\n\ttls internal",
            r.name,
            addrs.join(", ")
        );
        site_body(
            &mut out,
            r,
            &format!("login_ca {port}"),
            &format!("app_ca {up} {port} {host}"),
        );
        out.push_str("}\n");
    }
    // Only the public certificate is in /srv (the daemon copies it there); every path
    // serves that one file.
    let _ = writeln!(
        out,
        "\n# Download hearth's certificate: http://<ip>:{CERT_PORT}\nhttp://:{} {{\n\troot * /srv\n\t\
         rewrite * /hearth-ca.crt\n\theader Content-Type application/x-x509-ca-cert\n\t\
         header Content-Disposition \"attachment; filename=hearth-ca.crt\"\n\tfile_server\n}}",
        ca_port(CERT_PORT)
    );
    out
}

